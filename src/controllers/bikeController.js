const { AppError } = require('../middleware/errorHandler');
const {
  ALLOWED_BIKE_STATUSES,
  CREATION_BIKE_STATUSES,
  ensureJsonObject,
  parsePositiveInt,
  parseRequiredString,
} = require('../utils/validators');

/**
 * Validates bike status against a list of allowed statuses.
 */
function parseBikeStatus(value, allowedStatuses) {
  if (typeof value !== 'string') {
    throw new AppError(
      `status must be one of: ${allowedStatuses.join(', ')}`,
      400
    );
  }

  const normalized = value.trim().toLowerCase();
  if (!allowedStatuses.includes(normalized)) {
    throw new AppError(
      `status must be one of: ${allowedStatuses.join(', ')}`,
      400
    );
  }

  return normalized;
}

/**
 * Controller for Bike CRUD and search endpoints.
 */
function createBikeController(bikeModel) {
  async function getAllBikes(req, res, next) {
    try {
      let typeFilter;
      if (req.query.type !== undefined) {
        if (typeof req.query.type !== 'string' || !req.query.type.trim()) {
          throw new AppError(
            'Query parameter "type" must be a non-empty string',
            400
          );
        }
        typeFilter = req.query.type.trim();
      }

      const bikes = await bikeModel.getAllBikes({ type: typeFilter });
      return res.status(200).json(bikes);
    } catch (err) {
      return next(err);
    }
  }

  async function getBikeById(req, res, next) {
    try {
      const id = parsePositiveInt(req.params.id, 'id');
      const bike = await bikeModel.getBikeById(id);

      if (!bike) {
        throw new AppError(`Bike with id ${id} not found`, 404);
      }

      return res.status(200).json(bike);
    } catch (err) {
      return next(err);
    }
  }

  async function createBike(req, res, next) {
    try {
      ensureJsonObject(req.body);

      // Never accept bike_code from the client
      if (Object.prototype.hasOwnProperty.call(req.body, 'bike_code')) {
        throw new AppError(
          'bike_code is auto-generated by the server and cannot be provided by the client',
          400
        );
      }

      const name = parseRequiredString(req.body.name, 'name', 100);
      const type = parseRequiredString(req.body.type, 'type', 60);
      const status =
        req.body.status !== undefined
          ? parseBikeStatus(req.body.status, CREATION_BIKE_STATUSES)
          : 'available';

      const bike = await bikeModel.createBike({ name, type, status });
      return res.status(201).json(bike);
    } catch (err) {
      return next(err);
    }
  }

  async function updateBike(req, res, next) {
    try {
      const id = parsePositiveInt(req.params.id, 'id');
      ensureJsonObject(req.body);

      // Never accept or change bike_code during updates
      if (Object.prototype.hasOwnProperty.call(req.body, 'bike_code')) {
        throw new AppError(
          'bike_code cannot be modified or provided during bike updates',
          400
        );
      }

      const updates = {};

      if (req.body.name !== undefined) {
        updates.name = parseRequiredString(req.body.name, 'name', 100);
      }
      if (req.body.type !== undefined) {
        updates.type = parseRequiredString(req.body.type, 'type', 60);
      }
      if (req.body.status !== undefined) {
        updates.status = parseBikeStatus(
          req.body.status,
          ALLOWED_BIKE_STATUSES
        );
      }

      if (Object.keys(updates).length === 0) {
        throw new AppError(
          'Provide at least one updatable field: name, type, or status',
          400
        );
      }

      const updated = await bikeModel.updateBike(id, updates);
      if (!updated) {
        throw new AppError(`Bike with id ${id} not found`, 404);
      }

      return res.status(200).json(updated);
    } catch (err) {
      return next(err);
    }
  }

  async function deleteBike(req, res, next) {
    try {
      const id = parsePositiveInt(req.params.id, 'id');
      const deleted = await bikeModel.deleteBike(id);

      if (!deleted) {
        throw new AppError(`Bike with id ${id} not found`, 404);
      }

      return res.status(200).json({
        message: 'Bike deleted successfully',
        bike: deleted,
      });
    } catch (err) {
      return next(err);
    }
  }

  return {
    getAllBikes,
    getBikeById,
    createBike,
    updateBike,
    deleteBike,
  };
}

module.exports = {
  createBikeController,
};

